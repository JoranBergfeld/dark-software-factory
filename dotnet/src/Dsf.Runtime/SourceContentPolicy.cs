using Dsf.Core.Onboarding;
using System.Text;
using System.Text.RegularExpressions;

namespace Dsf.Runtime;

internal static class SourceContentPolicy
{
    internal static SourceExclusion PathExclusion(SourceNode node)
    {
        if (node.Mode is "120000" or "160000") return SourceExclusion.External;
        var segments = node.Path.Split('/');
        if (segments.Any(segment => segment.Equals(".env", StringComparison.OrdinalIgnoreCase)
            || segment.StartsWith(".env.", StringComparison.OrdinalIgnoreCase)
            || segment is ".ssh" or ".aws" or ".azure" or ".kube" or ".git-credentials" or ".netrc" or ".npmrc" or ".pypirc"
                or "id_rsa" or "id_ed25519" or "application_default_credentials.json"
            || segment.Equals("credentials", StringComparison.OrdinalIgnoreCase) || segment.Equals("secrets", StringComparison.OrdinalIgnoreCase)
            || segment.StartsWith("credentials.", StringComparison.OrdinalIgnoreCase) || segment.StartsWith("secrets.", StringComparison.OrdinalIgnoreCase)
            || segment.EndsWith(".pem", StringComparison.OrdinalIgnoreCase) || segment.EndsWith(".key", StringComparison.OrdinalIgnoreCase)
            || segment.EndsWith(".pfx", StringComparison.OrdinalIgnoreCase) || segment.EndsWith(".p12", StringComparison.OrdinalIgnoreCase)))
            return SourceExclusion.Sensitive;
        if (segments.Any(s => s is "vendor" or "node_modules" or "third_party" or "third-party" or ".venv"))
            return SourceExclusion.Vendor;
        return SourceExclusion.None;
    }

    internal static SourceExclusion ContentExclusion(byte[] bytes)
    {
        if (bytes is [0xff, 0xfe, ..] or [0xfe, 0xff, ..] or [0, 0, 0xfe, 0xff, ..]) return SourceExclusion.Unavailable;
        if (bytes.Contains((byte)0)) return SourceExclusion.Binary;
        string text;
        try { text = new UTF8Encoding(false, true).GetString(bytes); }
        catch (DecoderFallbackException) { return SourceExclusion.Unavailable; }
        if (text.StartsWith("version https://git-lfs.github.com/spec/v1", StringComparison.Ordinal)) return SourceExclusion.External;
        if (Sensitive(text)) return SourceExclusion.Sensitive;
        if (text.AsSpan(0, Math.Min(1024, text.Length)).Contains("<auto-generated>", StringComparison.OrdinalIgnoreCase)
            || text.AsSpan(0, Math.Min(1024, text.Length)).Contains("Code generated", StringComparison.OrdinalIgnoreCase)
                && text.AsSpan(0, Math.Min(1024, text.Length)).Contains("DO NOT EDIT", StringComparison.OrdinalIgnoreCase))
            return SourceExclusion.Generated;
        return SourceExclusion.None;
    }

    internal static bool Sensitive(string text) => FactorySourceEvidenceIntegrity.Sensitive(text);
}
